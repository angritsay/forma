#!/usr/bin/env node
/**
 * Concatenate the migrations into one file the Supabase SQL editor can take in a single paste.
 *
 *   node scripts/db/bundle.mjs
 *
 * The migrations exist separately because that is how they are applied by the CLI and how
 * they are reviewed. But a first-time setup through the dashboard means opening each one, pasting,
 * running, and checking the result once per file — that many chances to paste the wrong file or run
 * them out of order, and the order matters: 0002 defines functions over tables 0001 creates.
 *
 * The bundle is generated, never edited. Change a migration and re-run this.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';

const MIGRATIONS = 'supabase/migrations';
const DEST = 'supabase/setup-all.sql';

/** In application order. 0002 references what 0001 creates, 0005 redefines a view from 0002. */
const FILES = [
  ['0001_init.sql', 'tables, triggers, row-level security, grants'],
  ['0002_functions.sql', 'create_order, entitlements, admin RPCs, leaderboard'],
  ['0003_storage.sql', 'the private videos bucket and its access policies'],
  ['0004_content_seed.sql', 'the course and workout catalogue the backend enforces'],
  ['0005_subscriptions.sql', 'monthly / annual subscriptions and the entitlements union'],
];

const rule = '-- ' + '='.repeat(77);

const head = `${rule}
-- Forma — complete database setup, in one paste.
--
-- GENERATED by scripts/db/bundle.mjs from supabase/migrations/*.sql. Do not edit this file;
-- edit the migrations and re-run \`npm run db:bundle\`. They stay the source of truth.
--
-- HOW TO RUN
--   Supabase dashboard -> SQL Editor -> New query -> paste all of this -> Run.
--   It should finish with "Success. No rows returned".
--
-- Safe to re-run: every statement is guarded (create ... if not exists, drop policy if exists),
-- which is also how an existing project is upgraded.
--
-- ONE THING TO EDIT: the last section makes the coach an admin. Put his real sign-in address
-- there before running, or the admin screen — where purchases are activated — stays locked.
${rule}
`;

const tail = `
${rule}
-- Admin access — EDIT THIS BEFORE RUNNING
--
-- Replace the address with the one the coach will sign in with. Case does not matter (the column
-- is citext). Add a line per person who needs the admin screen.
${rule}

insert into public.admins (email) values ('CHANGE-ME@example.com')
on conflict (email) do nothing;
`;

const parts = [head];
for (const [name, what] of FILES) {
  parts.push(`\n${rule}\n-- ${name} — ${what}\n${rule}\n\n`);
  parts.push(`${readFileSync(join(MIGRATIONS, name), 'utf8').trimEnd()}\n`);
}
parts.push(tail);

mkdirSync(dirname(DEST), { recursive: true });
const sql = parts.join('');
writeFileSync(DEST, sql);

console.log(`${DEST}  ${sql.split('\n').length} lines, ${(sql.length / 1024).toFixed(0)} KB`);
console.log(`bundled: ${FILES.map(([f]) => f).join(', ')}`);
