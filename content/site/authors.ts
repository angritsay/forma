/**
 * Кто ведёт тренировку. Заполняет владелец.
 *
 * ## Зачем это отдельно от `coach.ts`
 *
 * `COACH` — это Сергей как лицо продукта: регалии, фотография на главной, страница «Тренер». Он
 * один и будет один: страница про него, а не про список.
 *
 * Здесь другое — **подпись под работой**. Владелец: «по хорошему бы запоминать от кого тренировка,
 * через кого она создавалась и показывать это пользователю, потому что я также хочу сделать с
 * йогой потом». Йогу ведёт не Сергей, и человек, открывший её, должен видеть чьё это, а не гадать.
 *
 * Сергей здесь берёт имя и фотографию из `COACH`, а не повторяет их: два места, где написано, как
 * его зовут, однажды разойдутся.
 *
 * ## Кто такой автор, а кто нет
 *
 * Автор — тот, **чья** это работа, а не тот, кто нажал «Сохранить». Второе база и так помнит
 * (`custom_workouts.author_id` — аккаунт, из которого сохранили), но это разные факты и они
 * расходятся ровно в том случае, ради которого всё затевалось: тренировки инструктора по йоге
 * заводит владелец, а не инструктор. Поэтому автора **выбирают** в редакторе, а не выводят из
 * того, кто вошёл.
 *
 * ## Почему список здесь, а не в базе
 *
 * Их двое и меняются они раз в полгода. Таблица, экран для неё и загрузка фотографий стоили бы
 * дороже всего, что они дают. Третий появится — добавляется строчка сюда.
 *
 * **Почты тут нет и не будет.** Репозиторий публичный (docs/SETUP.md §8), и адрес, попавший сюда,
 * остаётся в истории навсегда. Связи «этот админ — этот автор» здесь тоже нет: она не нужна,
 * потому что автора не угадывают, а выбирают.
 *
 * ## Что вписывать
 *
 * `id` — короткое латинское слово, оно уходит в базу и потом не меняется.
 * `name` — как подписывать. `role` — одна строка, чем человек занимается; пусто — строки нет.
 * `photo` — файл под `/public`; пусто — рисуется кружок с инициалом.
 */
import type { L10n } from '@/content/schema';
import { COACH } from './coach';

export interface Author {
  /** Уходит в базу. Менять нельзя: на него ссылаются сохранённые тренировки. */
  id: string;
  name: L10n;
  /** Одна строка под именем. Пусто — строки нет. */
  role?: L10n;
  /** Путь под /public, например '/coach/sergey.jpg'. Пусто — кружок с инициалом. */
  photo?: string;
}

export const AUTHORS: readonly Author[] = [
  {
    id: 'sergey',
    name: COACH.name,
    role: COACH.formaRole,
    photo: COACH.photo,
  },
  {
    /*
     * Владелец. Своими словами о себе — её, не мои: `role` пустая, пока она её не напишет, и тогда
     * под именем просто ничего нет. Выдумать за человека строчку о том, чем он занимается, — это
     * ровно то, что `docs/SPEC.md` запрещает делать с фактами о тренере.
     *
     * Фотографии тоже нет: пока не пришлёт, рисуется кружок с инициалом, и это нормальный вид, а
     * не дырка.
     */
    id: 'nastia',
    name: { ru: 'Настя', en: 'Nastia' },
  },
];

const BY_ID = new Map(AUTHORS.map((a) => [a.id, a]));

/** Автор по id, или `null` — если строку из базы уже некем подписать. */
export function authorById(id: string | null | undefined): Author | null {
  return id ? (BY_ID.get(id) ?? null) : null;
}
