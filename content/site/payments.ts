/**
 * Как платит тот, кто не может заплатить в рублях. Заполняет владелец; пока пусто — страница
 * честно показывает только «напиши мне».
 *
 * ## Почему это отдельная дорога, а не вторая кнопка в кассе
 *
 * Сайт с сентября выходит на двух языках, а касса одна: Prodamus, по-русски, в рублях. Английский
 * читатель доходил до кнопки «купить» и упирался в стену ровно в тот момент, когда собрался
 * платить. Решение владельца: вести его на страницу с инструкцией — перевод на PayPal, в
 * комментарии та почта, с которой он регистрировался, — и кнопку «написать мне», чтобы она могла
 * помочь, если что-то пойдёт не так.
 *
 * ## Что это значит для учёта
 *
 * **Вебхука здесь нет.** Prodamus присылает уведомление и `prodamus-webhook` открывает доступ сам;
 * PayPal про Forma не знает ничего. Значит каждый такой платёж — это ручная выдача доступа в
 * админке («Покупки» и «Подписки»), и почта в комментарии к переводу — единственное, что связывает
 * деньги с человеком. Поэтому инструкция просит её дважды: на странице и в самой форме перевода.
 *
 * Чека тоже нет: это не российская розница и не Prodamus с его фискализацией. Здесь про это
 * сказать нечего, кроме того, что это другая дорога и она ручная.
 *
 * ## Что куда вписывать
 *
 * `paypal` — ссылка целиком, `https://paypal.me/…` или страница оплаты. Пусто — блок про перевод
 * не рисуется вовсе, и остаётся только «напиши мне»: половинчатая инструкция хуже, чем её
 * отсутствие.
 *
 * `helpTelegram` — **твой** телеграм, не Сергея: помогать с доступом и деньгами будешь ты.
 * Ссылкой целиком: `https://t.me/username`.
 *
 * `note` — если хочется добавить что-то своё (валюта, в которой удобнее, сумма в долларах).
 * Необязательно; пусто — строки просто нет.
 */
import type { L10n } from '@/content/schema';

export const PAYMENTS = {
  /** Полная ссылка на PayPal. Пусто — блок про перевод не показывается. */
  paypal: '',
  /** Твой телеграм, полной ссылкой. Пусто — кнопки «написать мне» не будет. */
  helpTelegram: '',
  /** Необязательная строка от себя: валюта, сумма, что угодно. */
  note: undefined as L10n | undefined,
} as const;

/** Есть ли что показать про перевод. */
export function hasPaypal(): boolean {
  return PAYMENTS.paypal.trim().startsWith('https://');
}

/** Есть ли куда написать за помощью. */
export function hasPaymentHelp(): boolean {
  return PAYMENTS.helpTelegram.trim().startsWith('https://');
}
