/** Ключ курса в таблице выше. */
export function courseKey(courseId: string): string {
  return `course:${courseId}`;
}

/** Ключ тарифа в таблице выше. */
export function planKey(planId: string): string {
  return `plan:${planId}`;
}

/**
 * Ключ занятия с тренером — получаса или часа (`content/site/booking.ts`).
 *
 * Владелец: «в лава топ не добавлены продажи на 30 минут и на 60 минут Сергея». Кнопка «оплатить»
 * на вкладке тренера читает этот ключ ровно так же, как кнопка курса читает свой; пока товаров в
 * кабинете нет, ключа нет и в таблице, {@link lavaUrl} отвечает `null`, и нерусскому читателю
 * предлагается написать тренеру — то же, что было до lava.top вообще.
 *
 * Занятие — не курс и не подписка: открывать по нему нечего, время назначает человек. Вебхук это
 * знает и на таком товаре не трогает ни курсы, ни подписку, а только записывает платёж
 * (`supabase/functions/lava-webhook/index.ts`).
 */
export function sessionKey(optionId: string): string {
  return `session:${optionId}`;
}

/** Ссылка на товар, или `null` — товар в lava.top ещё не заведён. */
export function lavaUrl(key: string): string | null {
  const url = LAVA_PRODUCTS[key]?.productUrl.trim() ?? '';
  // Та же проверка, что у любой платёжной ссылки в продукте: только абсолютный https.
  return url.startsWith('https://') ? url : null;
}
