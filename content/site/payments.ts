/** Ключ курса в таблице выше. */
export function courseKey(courseId: string): string {
  return `course:${courseId}`;
}

/** Ключ тарифа в таблице выше. */
export function planKey(planId: string): string {
  return `plan:${planId}`;
}

/** Ссылка на товар, или `null` — товар в lava.top ещё не заведён. */
export function lavaUrl(key: string): string | null {
  const url = LAVA_PRODUCTS[key]?.productUrl.trim() ?? '';
  // Та же проверка, что у любой платёжной ссылки в продукте: только абсолютный https.
  return url.startsWith('https://') ? url : null;
}
