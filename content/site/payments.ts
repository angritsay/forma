/**
 * Касса для тех, кто платит не в рублях: lava.top. Заполняет владелец.
 *
 * ## Что было до неё
 *
 * Сайт выходит на двух языках, а касса была одна — Prodamus, по-русски и в рублях. Английский
 * читатель упирался в неё ровно тогда, когда собрался платить. Первым решением была страница с
 * инструкцией: перевод на PayPal, почта в комментарии, доступ руками. Это работало бы, но каждый
 * такой платёж — пять минут владельца и почта в комментарии как единственная ниточка между
 * деньгами и человеком.
 *
 * Владелец: «давай подключим лава топ вместо всех приколов с пейпалом и инструкциями». lava.top
 * принимает иностранные карты, считает в долларах и евро — **и присылает вебхук**, то есть доступ
 * открывается сам, как с Prodamus.
 *
 * ## Prodamus остаётся
 *
 * Для рублёвых покупателей не меняется ничего, и это не лень. Prodamus фискализирует — выдаёт
 * чеки, которых требует российская розница. Перевести туда же и российские платежи — отдельное
 * решение с бухгалтерией внутри, а не правка конфига.
 *
 * ## Что сюда вписывать
 *
 * `productUrl` — публичная ссылка на товар, та, что lava.top даёт в кабинете.
 *
 * `productId` — идентификатор того же товара **внутри** lava.top. Он приезжает в вебхуке полем
 * `product.id`, и по нему функция понимает, что именно оплатили. Без него платёж дойдёт, а
 * открывать будет нечего.
 *
 * Ключ — наш собственный: `course:<id курса>` или `plan:<id тарифа>`.
 *
 * Пусто — кнопка «купить» на неродном языке ведёт туда же, куда ведёт любая отсутствующая ссылка
 * на оплату в этом продукте: к адресу поддержки. Ни PayPal, ни инструкций больше нет.
 *
 * **Ключа API здесь нет и быть не может.** Сайт статический и публичный: всё в этом файле читает
 * кто угодно. Ссылка на товар публична по своей природе, а ключ и секрет вебхука живут секретами
 * Supabase (`docs/SETUP.md` §7.9).
 */

export interface LavaProduct {
  /** Публичная ссылка на товар в lava.top. */
  productUrl: string;
  /** Идентификатор товара внутри lava.top — приходит в вебхуке как `product.id`. */
  productId: string;
}

