/**
 * Привязка телеграм-аккаунта к профилю — одна из двух половин того, чтобы бот вообще мог написать.
 *
 * Бот знает chat id только тех, кто сам ему написал; приложение знает почту. Пока эти две
 * половины не сведены, любое сообщение — про оплату, про выданную тренировку, про победителя
 * недели — отправлять некуда.
 *
 * ## Почему это запрос к функции, а не запись в таблицу
 *
 * Свой telegram id клиент знает: он лежит в `Telegram.WebApp.initDataUnsafe`. Поле называется
 * `unsafe` не для красоты — это просто разобранная строка запуска, и подделать её в отладчике
 * умеет кто угодно. Поэтому клиент не сообщает свой id, а пересылает **подписанную** строку целиком;
 * проверяет подпись edge-функция `link-telegram`, потому что для проверки нужен токен бота, а он
 * секрет Supabase и в этот репозиторий (публичный) не попадает никогда.
 *
 * Отказ здесь никогда не громкий: человек открыл приложение, чтобы тренироваться, а не чтобы
 * чинить уведомления. Не привязалось — просто не привязалось, попробуем при следующем запуске.
 */
import { supabase } from './client';
import { isDemo } from './mode';

/**
 * Привязать текущий телеграм-аккаунт к вошедшему профилю.
 *
 * `true` — привязали (или уже было привязано и подтвердилось). Всё остальное — `false`, без
 * подробностей: причина отказа наружу не выходит.
 */
export async function linkTelegram(initData: string): Promise<boolean> {
  if (isDemo() || !initData) return false;
  try {
    const { data, error } = await supabase().functions.invoke<{ linked?: boolean }>(
      'link-telegram',
      { body: { initData } },
    );
    if (error) return false;
    return data?.linked === true;
  } catch {
    return false;
  }
}
