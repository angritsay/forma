/**
 * Упражнение крупно, ещё до того, как тренировка началась.
 *
 * Владелец: «по хорошему при клике на упражнение открывать карточку превью упражнения, так же как
 * оно бы выглядело на тренировке, только в мордалке на 90 процентов экрана с затемнением на фоне».
 *
 * ## «Так же, как на тренировке» — буквально
 *
 * Внутри стоит `ExerciseBack` — та самая обратная сторона карточки, которую человек видит в
 * плеере, перевернув её: «Техника», «Рекомендации», «Осторожно», слово в слово и вкладка во
 * вкладку. Не похожий экран, а тот же компонент: разойтись они не могут, потому что они один.
 *
 * Сверху — кадр из клипа, `ExerciseStill`, тот же, что в плеере стоит фоном. Движение по
 * названию узнают не все, и «мостик на одной ноге» без картинки — это строчка, которую человек
 * пролистывает, а не движение, которое он себе представил.
 *
 * ## Почему 90% и с затемнением
 *
 * Так попросили, и это правильно для того, зачем сюда заходят: посмотреть одно упражнение и
 * вернуться в список. Полный экран увёл бы со страницы и потребовал «назад»; шторка снизу на треть
 * экрана не вместила бы три вкладки текста. Затемнение оставляет список видимым позади — видно,
 * что ты никуда не ушёл.
 *
 * Нагрузка передаётся вместе с упражнением: «Осторожно» зависит от неё — то, что безопасно налегке,
 * с весом может быть противопоказано. Показать общие противопоказания вместо тех, что относятся к
 * сегодняшнему подходу, было бы хуже, чем не показать ничего.
 */
import { Modal } from '@/components/ui/Modal';
import { ExerciseStill } from '@/components/media/ExerciseStill';
import { findExercise } from '@/content/catalogue';
import type { PrescribedItem } from '@/lib/training/types';
import { useT } from '@/app/hooks/useT';
import { ExerciseBack } from '@/app/features/player/CardBack';

export interface ExercisePreviewProps {
  /** Упражнение и его нагрузка, или `null` — окно закрыто. */
  item: PrescribedItem | null;
  onClose: () => void;
}

export function ExercisePreview({ item, onClose }: ExercisePreviewProps) {
  const { l } = useT();
  const exercise = item ? findExercise(item.exerciseId) : null;

  return (
    <Modal
      open={item !== null}
      onClose={onClose}
      title={exercise && item ? l(exercise.name) : ''}
      /*
       * 90% высоты экрана, а не «сколько получится»: у одних упражнений текста на два экрана, у
       * других на две строки, и окно, прыгающее по высоте от движения к движению, читается как
       * сбой.
       *
       * `calc(90dvh - 3rem)`, потому что `Modal` держит панель в контейнере с `p-6`: ровно 90dvh
       * вместе с этими полями не поместились бы в экран и вылезли бы за край.
       *
       * `flex flex-col` — панель по умолчанию складывает всё по естественной высоте, и при
       * заданной высоте содержимое не растянулось бы: снизу осталась бы пустота, а прокрутки не
       * появилось бы вовсе.
       */
      className="flex h-[calc(90dvh-3rem)] flex-col"
      bodyClassName="min-h-0 flex-1 overflow-y-auto"
    >
      {item && exercise ? (
        <div className="flex flex-col gap-5">
          {/*
            Кадр во всю ширину и 4:3 — то же соотношение, в котором клип стоит в плеере. Он
            декоративный: название уже стоит заголовком окна, и второй раз его читать незачем.
          */}
          <div className="-mx-1 aspect-[4/3] overflow-hidden rounded-card bg-surface-2">
            <ExerciseStill exerciseId={item.exerciseId} loading="eager" />
          </div>
          <ExerciseBack exerciseId={item.exerciseId} item={item} />
        </div>
      ) : null}
    </Modal>
  );
}
