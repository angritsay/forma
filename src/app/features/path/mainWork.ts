/**
 * Что показывать в плане перед тренировкой, а что нет.
 *
 * Владелец, глядя на список перед выданной тренировкой: «Показывай такое же перед каждой
 * тренировкой, только скрывай разминку и заминку».
 *
 * ## Почему именно их
 *
 * План перед тренировкой отвечает на один вопрос: **что я сейчас буду делать.** Круги шеей и
 * растяжка сгибателей бедра на него не отвечают — они одинаковые почти всегда и в решении
 * «браться сейчас или вечером» не участвуют. Зато они длинные: в примере из задания разминка и
 * заминка — это восемь строк из тринадцати, и работа тонет между ними.
 *
 * Из тренировки они никуда не деваются: их по-прежнему проходят, их просто не пересказывают
 * заранее.
 *
 * ## Два представления одного и того же
 *
 * Курс приходит блоками (`PrescribedBlock.type`), тренировка из конструктора — секциями
 * (`CustomWorkoutSection.kind`). Слова в обоих одни и те же, и решение тоже одно, поэтому оно
 * живёт здесь, а не двумя одинаковыми условиями на двух экранах, которые потом разойдутся.
 *
 * ## Если работы не осталось
 *
 * Тренировка из одной разминки — это редкость, но она возможна: день мобилити, например. Тогда
 * фильтр вернул бы пустоту, и экран показал бы пустое место там, где обещал план. Поэтому
 * `mainOnly` в таком случае отдаёт всё: лучше показать разминку, чем ничего.
 */

/** Части, которые в плане не пересказываются. */
const ASIDE = new Set(['warmup', 'cooldown']);

/**
 * Только рабочая часть — или всё, если рабочей части нет.
 *
 * @param parts блоки курса или секции конструктора
 * @param kindOf чем размечена часть: `type` у блока, `kind` у секции
 */
export function mainOnly<T>(parts: readonly T[], kindOf: (part: T) => string): T[] {
  const work = parts.filter((p) => !ASIDE.has(kindOf(p)));
  return work.length > 0 ? work : [...parts];
}

/** Скрыли ли мы что-нибудь: экран говорит об этом строчкой, а не молчит. */
export function hasAside<T>(parts: readonly T[], kindOf: (part: T) => string): boolean {
  return parts.length !== mainOnly(parts, kindOf).length;
}
