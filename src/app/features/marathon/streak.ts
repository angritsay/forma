/**
 * Серия в клубе: сколько дней подряд человек сдавал задание. Чистый модуль, покрыт тестами.
 *
 * Владелец: «в клубе как раз-таки можно сделать вот эту историю со стриком и показывать, сколько
 * дней подряд ты выполняешь упражнения».
 *
 * **Серия здесь уже была и была вынута** — «стрик нам не подходит… человеку не надо каждый день
 * так заниматься» (`CoursesHead.tsx` хранит эту цитату). Тот стрик считал тренировки, а тренировок
 * каждый день и правда быть не должно. Этот считает задание клуба, которое по замыслу ежедневное и
 * маленькое: «10 минут пешком, 20 приседаний, стакан воды до кофе». Счётчик честен ровно потому,
 * что считает то, что и так делается каждый день.
 *
 * ## Правила, и все три — решение владельца
 *
 * 1. **Граница недели серию не рвёт.** «Воскресенье и конец недели не ругают серию.» Клуб идёт
 *    недельными раундами, каждый раунд — своя строка в `marathons`, и считать внутри раунда
 *    значило бы обнулять счётчик каждое воскресенье. `my_club_days()` (0023) отдаёт даты по всем
 *    раундам сразу, а здесь они просто идут подряд.
 * 2. **Сегодня ещё не сделано — это не разрыв.** День не потерян, пока он не кончился, поэтому
 *    серия, доходящая до вчера, считается живой. Иначе счётчик обнулялся бы каждое утро и
 *    возвращался к обеду, то есть показывал бы время суток, а не привычку.
 * 3. **Пропущенный день обнуляет.** Позавчера и раньше — уже прошлое; серия начинается заново.
 *
 * Считает клиент, а не база, и это тоже решение: правило одно, и живёт оно в одном месте. База
 * отвечает на вопрос без вариантов — в какие дни есть незачёркнутый пруф, — а демо-режим отвечает
 * тем же списком из своей базы и попадает сюда же.
 */

/** Календарная дата как `YYYY-MM-DD` — та форма, в которой её отдаёт и Postgres, и демо-режим. */
export type IsoDay = string;

const DAY_MS = 24 * 60 * 60 * 1000;

/** `YYYY-MM-DD` → число дней от эпохи. Полдень UTC, чтобы летнее время не сдвинуло день. */
function dayNumber(iso: IsoDay): number | null {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso.trim());
  if (!m) return null;
  const t = Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3]), 12);
  return Number.isFinite(t) ? Math.round(t / DAY_MS) : null;
}

/**
 * Длина серии, которая **упирается в сегодня**: дни подряд, заканчивающиеся сегодняшним или
 * вчерашним днём. Всё, что оборвалось раньше, — это прошлая серия, и она не показывается.
 *
 * `days` может приходить в любом порядке и с повторами: и то и другое здесь не важно.
 */
export function clubStreak(days: readonly IsoDay[], today: IsoDay): number {
  const end = dayNumber(today);
  if (end === null) return 0;

  const seen = new Set<number>();
  for (const d of days) {
    const n = dayNumber(d);
    // День из будущего в серию не идёт: он ещё не наступил, и считать его значило бы обещать.
    if (n !== null && n <= end) seen.add(n);
  }
  if (seen.size === 0) return 0;

  // Где серия кончается: сегодня, если сегодня сделано, иначе вчера. Правило 2.
  const last = seen.has(end) ? end : seen.has(end - 1) ? end - 1 : null;
  if (last === null) return 0;

  let n = 0;
  while (seen.has(last - n)) n += 1;
  return n;
}

/**
 * Сделано ли задание **сегодня** — отдельный вопрос от длины серии.
 *
 * Нужен интерфейсу, потому что «3 дня подряд» значит разное до и после сегодняшнего задания: в
 * первом случае серия держится на вчера и сегодня её можно потерять, во втором она уже продлена.
 */
export function clubStreakDoneToday(days: readonly IsoDay[], today: IsoDay): boolean {
  const end = dayNumber(today);
  if (end === null) return false;
  return days.some((d) => dayNumber(d) === end);
}
