/**
 * Кто что может открыть в курсе. Чистый модуль, покрыт тестами.
 *
 * До этого «можно» значило «куплен», и проверка стояла в четырёх местах: список курсов, путь,
 * превью узла и — единственная настоящая — insert-политика `workout_sessions`. Три из четырёх
 * давали один и тот же ответ разными словами, и когда правило усложнилось, они бы разошлись.
 *
 * Правило теперь такое: **первая тренировка курса бесплатна, и её можно повторять сколько
 * угодно.** Владелец: «Сделай возможность пользователю перепроходить первую тренировку и всегда
 * в бесплатном режиме, не требуя оплаты.» Раньше проба тратилась: закончил — и та же самая
 * тренировка закрывалась вместе со всеми остальными, что выглядит как отобранный подарок, а не
 * как граница платного.
 *
 * Оно совпадает с тем, что делает база (`can_train_free_node()` в 0022): на некупленном курсе
 * можно тренировать тот узел, который уже тренировали, и никакой другой. Разница ровно одна, и
 * она в пользу строгости: база не знает порядка узлов и разрешила бы выбрать бесплатным любой, а
 * здесь бесплатен только первый.
 *
 * **Второе правило, и оно новое:** до оплаты любой узел, кроме первого, ведёт на цену — включая
 * тот, до которого человек «ещё не дошёл». Владелец: «до оплаты курса он может кликать, и мы
 * будем его перенаправлять на пейволл, за исключением первой тренировки». Порядок остаётся для
 * того, кто курс купил; тому, кто не купил, «сначала пройди предыдущие» отвечает не на тот
 * вопрос, который он задал, нажав на двадцатый день.
 */
import type { Course, CourseNode } from '@/content/schema';

export type CourseAccess =
  /** Куплен или открыт подпиской: всё доступно. */
  | 'owned'
  /** Не куплен, бесплатная тренировка ещё не сделана. */
  | 'trial'
  /** Не куплен, бесплатная сделана — её можно повторить, остальное за деньги. */
  | 'tried';

export interface CourseAccessInput {
  /** Есть ли активная покупка / подписка на этот курс. */
  owned: boolean;
  /** Завершена ли хотя бы одна тренировка этого курса. */
  hasCompleted: boolean;
}

/**
 * Состояние курса для **текстов**, а не для доступа.
 *
 * `'tried'` больше не значит «заперто»: сделавший бесплатную тренировку может сделать её снова.
 * Значит оно ровно одно — «уже пробовал», — и нужно затем, чтобы карточка курса не обещала ему
 * «Попробовать бесплатно» в третий раз, а сразу называла цену. Что именно открыто, отвечает
 * `nodeAccess`, и он этого поля не читает.
 */
export function courseAccess({ owned, hasCompleted }: CourseAccessInput): CourseAccess {
  if (owned) return 'owned';
  return hasCompleted ? 'tried' : 'trial';
}

/**
 * Первый узел, который вообще можно тренировать, — им и открывается проба.
 *
 * Не `nodes[0]`: у курса первым может стоять день отдыха или веха, а они не тренировки и пробой
 * быть не могут. У «Формы с нуля» первый узел и так тренировка (вступительного теста в ней нет),
 * но это свойство одного курса, а не правило.
 */
export function firstTrainableNode(course: Course): CourseNode | null {
  return course.nodes.find((n) => n.kind !== 'rest' && n.kind !== 'milestone') ?? null;
}

export interface NodeAccessInput {
  /** Есть ли активная покупка / подписка на этот курс. */
  owned: boolean;
  course: Course;
  node: CourseNode;
}

/**
 * Можно ли открыть этот узел — и если нет, то потому что за него не заплачено.
 *
 * `'paywalled'` отделён от «ещё не дошёл» намеренно: это разные тупики и вести из них надо в
 * разные места. Но у некупившего второго тупика нет вовсе — до оплаты открыт ровно один узел, а
 * всё остальное упирается в цену, в каком бы порядке человек по ним ни нажимал.
 *
 * `hasCompleted` здесь больше не спрашивается, и это вся правка 0022: первый узел открыт и до
 * пробы, и после неё.
 */
export function nodeAccess({ owned, course, node }: NodeAccessInput): 'open' | 'paywalled' {
  if (owned) return 'open';
  const first = firstTrainableNode(course);
  return first !== null && first.id === node.id ? 'open' : 'paywalled';
}

/**
 * Сделана ли уже бесплатная тренировка — по ответу сервера, а не по локальному окну сессий.
 *
 * `recentSessions` в сторе прогресса — это двадцать последних записей. Человек, попробовавший
 * месяц назад и с тех пор много тренировавшийся, из этого окна выпадает, и карточка снова
 * обещала бы ему «Попробовать бесплатно». Поэтому источник — `my_trained_courses()` (0019),
 * посчитанный по всем строкам.
 */
export function hasCompletedIn(trainedCourseIds: readonly string[], courseId: string): boolean {
  return trainedCourseIds.includes(courseId);
}
