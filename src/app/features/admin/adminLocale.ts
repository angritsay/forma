/**
 * Какой язык тренер сейчас печатает в админке.
 *
 * ## Почему переключатель, а не второе поле рядом с каждым
 *
 * Полей много. У курса их пятнадцать — название, подзаголовок, описание, три списка, вопросы и
 * ответы, — и если поставить английское поле под каждым русским, форма станет вдвое длиннее, а
 * заполняют её всё равно по одному языку за раз: сначала по-русски, чтобы выпустить, потом
 * когда-нибудь по-английски. Переключатель наверху экрана оставляет форму той же длины и прямо
 * говорит, на каком языке сейчас пишут.
 *
 * ## Один на всю админку
 *
 * Переключил на английский в редакторе курса, зашёл в день — он тоже английский. Иначе перевод
 * курса превращается в переключение на каждом экране, а это ровно тот случай, когда бросают на
 * половине.
 *
 * Запоминается в `localStorage`: «сажусь переводить» — это занятие на вечер, а не на одну форму.
 * Русский по умолчанию: на нём пишут в первый раз, и на нём выходит продукт.
 *
 * ## Чего здесь нет
 *
 * Обязательности. Английское поле можно не заполнить: `l10n()` в `src/lib/courses/draft.ts`
 * подставит русское, и курс выйдет. Требовать перевод значило бы, что Сергей не может выпустить
 * день, пока не переведёт его, — а он тренер, а не переводчик.
 */
import { create } from 'zustand';
import { DEFAULT_LOCALE, isLocale, type Locale } from '@/i18n/index';

export const ADMIN_LOCALE_KEY = 'forma.adminLocale';

interface AdminLocaleState {
  editing: Locale;
  setEditing: (locale: Locale) => void;
}

function read(): Locale {
  try {
    const v = typeof localStorage !== 'undefined' ? localStorage.getItem(ADMIN_LOCALE_KEY) : null;
    if (isLocale(v)) return v;
  } catch {
    /* Приватный режим: пишем по-русски, как в первый раз. */
  }
  return DEFAULT_LOCALE;
}

export const useAdminLocale = create<AdminLocaleState>()((set) => ({
  editing: read(),
  setEditing: (locale) => {
    if (!isLocale(locale)) return;
    try {
      localStorage?.setItem(ADMIN_LOCALE_KEY, locale);
    } catch {
      /* Переживёт эту сессию в памяти. */
    }
    set({ editing: locale });
  },
}));

/* ---------------------------------------------------------------------------------------------
 * Чтение и запись одной половины L10n
 *
 * Три чистые функции вместо обёрток над `Input`: полей два десятка, и у каждого свой способ
 * положить значение обратно (в `content`, в элемент списка, в вопрос из FAQ). Обёртка потребовала
 * бы протащить через себя все эти способы; функции просто считают строку.
 * ------------------------------------------------------------------------------------------- */

/** Что показать в поле: половина на текущем языке, или пусто. */
export function pick(value: Partial<Record<Locale, string>> | undefined, locale: Locale): string {
  return value?.[locale] ?? '';
}

/**
 * Что положить обратно, сохранив вторую половину.
 *
 * Пустая строка **стирает** эту половину, а не кладёт `''`: пустая строка прошла бы через
 * `l10n()` как написанный текст и оставила бы английского читателя с пустым названием вместо
 * русского. Стёртой половины нет — и подстановка снова работает.
 */
export function put(
  value: Partial<Record<Locale, string>> | undefined,
  locale: Locale,
  next: string,
): Partial<Record<Locale, string>> {
  const out = { ...(value ?? {}) };
  if (next.trim()) out[locale] = next;
  else delete out[locale];
  return out;
}

/**
 * Что показать в подсказке поля: то же самое на другом языке.
 *
 * Это и есть весь интерфейс перевода. Переключил на английский — в каждом поле серым стоит
 * русский текст, который надо перевести, и видно, что именно поле пустое. Отдельной колонки
 * «а вот оригинал» не нужно: оригинал стоит там, куда смотрят.
 */
export function otherHalf(
  value: Partial<Record<Locale, string>> | undefined,
  locale: Locale,
): string {
  const other = locale === 'ru' ? 'en' : 'ru';
  return value?.[other] ?? '';
}
