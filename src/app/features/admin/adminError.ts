/**
 * Что показать тренеру, когда админка не смогла.
 *
 * ## Зачем это отдельно
 *
 * Каждый редактор здесь писал `catch { toast('Не удалось сохранить') }`. Ошибка выбрасывалась
 * целиком, вместе со всем, что в ней было сказано, — и человек оставался с фразой, которая
 * сообщает, что что-то случилось, и не сообщает ничего больше.
 *
 * Один случай это ломало особенно обидно, и он не редкий, а встроен в порядок выкладки: **код
 * уезжает в прод мержем, а миграции применяются руками кнопкой в Actions.** Между этими двумя
 * моментами приложение просит у базы колонку, которой в ней ещё нет, постгрест отвечает
 * `PGRST204` с именем колонки, и тренер видит «Не удалось сохранить». Час на догадки вместо одной
 * кнопки — именно так и вышло с `title_en` (0032).
 *
 * ## Что показывается
 *
 * Только этот случай и получает свой текст — с именем колонки из ответа постгреста и с названием
 * кнопки, которой это чинится. Всё остальное остаётся своей фразой экрана: «не удалось удалить» и
 * «не удалось сохранить» — разные вещи, и общий текст на них был бы шагом назад.
 *
 * Админку видят только тренер и владелец, и оба применяют миграции, поэтому техническая строчка
 * здесь на своём месте. Наружу, на экран входа, она не уходит: там `schema` сворачивается в общую
 * ошибку, потому что гостю с ней делать нечего.
 */
import { isAppError } from '@/lib/api/errors';
import type { TKey } from '@/i18n/index';
import type { Translator } from '@/app/hooks/useT';

/**
 * Текст тоста по ошибке и ключу, который этот экран показывает обычно.
 *
 * `fallback` — своя фраза экрана: она остаётся ответом на всё, кроме отставшей базы.
 */
export function adminErrorTitle(tr: Translator, e: unknown, fallback: TKey): string {
  if (isAppError(e) && e.code === 'schema') {
    return tr.t('app.adminSchemaBehind', { detail: e.message });
  }
  return tr.t(fallback);
}
