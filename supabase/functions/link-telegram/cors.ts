/**
 * Разрешение браузеру вообще сделать этот запрос.
 *
 * ## Чем это оказалось на практике
 *
 * Привязка телеграма не работала ни у кого: 0 из 17. Функция была выложена, миграция применена,
 * человек открывал мини-апп — и ничего. В журнале функции не было ни одной жалобы, потому что
 * жаловаться было не на что: **до разбора тела дело не доходило**. Во вкладке Invocations стояло
 * `OPTIONS → 405`, и только это.
 *
 * Приложение живёт на `forma-app.co`, функция — на `supabase.co`. Это разные источники, а запрос
 * несёт заголовки `authorization` и `content-type: application/json`, и значит браузер обязан
 * сперва спросить разрешения отдельным запросом `OPTIONS`. Обработчик отвечал `405` на всё, что не
 * `POST`, — то есть и на этот вопрос тоже. Получив отказ, браузер **не отправляет сам POST**: не
 * «отправляет и получает ошибку», а молча не отправляет. Снаружи это выглядит как «ничего не
 * произошло», изнутри — как будто никто не звонил.
 *
 * ## Почему `*`, а не список разрешённых адресов
 *
 * Соблазн перечислить свои домены понятен, но источник здесь ничего не охраняет. У функции две
 * двери, и обе настоящие: JWT говорит, чей это профиль, подпись `initData` — чей это телеграм
 * (`index.ts`). Заголовок `Origin` не даёт ни того, ни другого: его проставляет браузер для
 * браузера, и запрос откуда угодно ещё мимо браузера его просто не содержит.
 *
 * Зато список — машина для молчаливых поломок, и мы только что заплатили за это неделями
 * неработающих уведомлений. Завели превью-сборку, сменили домен, открыли с другого адреса — и всё
 * снова тихо перестаёт работать, ровно с тем же пустым журналом.
 *
 * `Access-Control-Max-Age` — чтобы предзапрос случался раз в сутки, а не на каждый запуск
 * приложения: привязка зовётся при каждом открытии, и платить двумя обращениями вместо одного
 * каждый раз незачем.
 */

/** Заголовки, которые должен нести каждый ответ, иначе браузер не отдаст его коду. */
export const CORS_HEADERS: Readonly<Record<string, string>> = {
  'access-control-allow-origin': '*',
  /*
   * `authorization` и `content-type` шлём мы сами; `apikey` и `x-client-info` добавляет
   * supabase-js, и без них в списке предзапрос завернёт уже браузер, а не функция.
   */
  'access-control-allow-headers': 'authorization, content-type, apikey, x-client-info',
  'access-control-allow-methods': 'POST, OPTIONS',
  'access-control-max-age': '86400',
};

/** Ответ на предзапрос, или `null` — если это не предзапрос и надо работать дальше. */
export function preflight(method: string): Response | null {
  if (method !== 'OPTIONS') return null;
  // 204: тело здесь не нужно никому, важны только заголовки.
  return new Response(null, { status: 204, headers: { ...CORS_HEADERS } });
}
